"""
Step 10: Copy the final offline_bundle/ to a single target folder for the app.

Input:
- ./offline_bundle/ (generated by step 08)

Output:
- <out_dir>/offline_bundle/ (ready to copy into the React Native app assets)
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from data_helpers._common import WORK_DIR  # noqa: E402


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--bundle_dir",
        default=str(WORK_DIR / "offline_bundle"),
        help="Path to offline bundle folder (default: ./temp_bundle_build/offline_bundle)",
    )
    p.add_argument(
        "--out_dir",
        default="",
        help="Target directory to copy into (e.g. your RN app assets folder). If empty, no copy is performed.",
    )
    args = p.parse_args()

    bundle_dir = Path(args.bundle_dir)
    out_dir = Path(args.out_dir)
    if not bundle_dir.exists():
        raise FileNotFoundError(f"bundle_dir not found: {bundle_dir}")

    if not str(args.out_dir).strip():
        print("[SKIP] No --out_dir provided. Bundle is ready at:")
        print(f"  {bundle_dir}")
        return

    out_dir = Path(args.out_dir)
    dst = out_dir / "offline_bundle"
    if dst.exists():
        shutil.rmtree(dst, ignore_errors=True)
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(bundle_dir, dst)

    print("[DONE]")
    print(f"  source: {bundle_dir}")
    print(f"  target: {dst}")


if __name__ == "__main__":
    main()

